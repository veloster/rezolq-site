# ---- Images generated from the motif -------------------------------------
C = lambda name: next(t['value'] for t in T['color']['tokens'] if t['name'] == name)
K = 1.08  # slant of the Q tail

def tail(x, y, w, h, fill, op=1):
    o = f' opacity="{op}"' if op != 1 else ''
    return f'<polygon points="{x:.1f},{y:.1f} {x+w:.1f},{y:.1f} {x+w+K*h:.1f},{y+h:.1f} {x+K*h:.1f},{y+h:.1f}" fill="{fill}"{o}/>'

def motif(W, H, cell=40, lit_fn=None, bg=None, dim=1):
    w, h, g = cell * 0.55, cell * 0.72, cell
    rows = int(H / g) + 1
    cols = int(W / g) + rows + 2
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}">']
    if bg: out.append(f'<rect width="{W}" height="{H}" fill="{bg}"/>')
    for r in range(rows):
        for c in range(-rows, cols):
            x = c * g - r * g * K + rows * g * K * 0.5
            y = r * g + (g - h) / 2
            if x + w + K * h < 0 or x > W: continue
            lit = lit_fn(x, r, c, rows) if lit_fn else False
            out.append(tail(x, y, w, h, (C('cyan') if c % 3 else C('citron')) if lit else C('pixel-eteint'), dim if lit else 1))
    out.append('</svg>')
    return ''.join(out)

def wave(W, amp=0.3, phase=0):
    def f(x, r, c, rows):
        t = round(rows / 2 + math.sin((x / W) * 2 * math.pi + phase) * rows * amp)
        return r == t or (r == t + 1 and c % 4 == 0)
    return f

